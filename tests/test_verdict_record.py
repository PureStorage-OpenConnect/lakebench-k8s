"""EVD-1: the verdict is decided from the record alone (DESIGN-v1.7 ch03
section 1, ER-3).

Every case starts from a pinned stored record (tests/fixtures/records) and
edits named fields. The six mutations of the acceptance read PASSED before
ER-3 (compute_verdict had no layer, rule, zero-ratio or empty-answer gate)
and FAILED after it, each on its own gate.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

import pytest

from lakebench.metrics import verdict as V
from tests.fixtures import stored_records as sr

ROOT = Path(__file__).resolve().parents[1]
C360_BATCH = "5105a0"  # C360 batch s10, PASSED
AML_BATCH = "1320bd"  # AML batch s1, PASSED, W1 skipped giant-component
AML_CONT = "ebb26f"  # AML continuous s1, PASSED
C360_CONT = "1d17f4"  # C360 continuous s1, PASSED


def _metrics(rec: dict):
    """*rec* loaded the way lakebench loads a stored run."""
    from lakebench.metrics.storage import MetricsStorage

    return MetricsStorage()._dict_to_metrics(rec)


def _job(rec: dict, job_type: str) -> dict:
    return [j for j in rec["jobs"] if j["job_type"] == job_type][-1]


def _stream(rec: dict, job_type: str) -> dict:
    return [s for s in rec["streaming"] if s["job_type"] == job_type][-1]


def _silver_zero(rec: dict) -> None:
    _job(rec, "silver-build")["output_rows"] = 0


def _gold_zero(rec: dict) -> None:
    _job(rec, "gold-finalize")["output_rows"] = 0
    rec["gold_size_gb"] = 0.0


def _answers_empty(rec: dict) -> None:
    for q in rec["benchmark"]["queries"]:
        q["rows_returned"] = 0


def _ratio_zero(rec: dict) -> None:
    # The loader reads the scorecard (scores is its alias); a save writes
    # the same value in all three places.
    pb = rec["pipeline_benchmark"]
    pb["scale_ratio"] = pb["scorecard"]["scale_ratio"] = pb["scores"]["scale_ratio"] = 0.0


def _rules_errored(rec: dict) -> None:
    gold = _job(rec, "gold-finalize")
    gold["rule_errors"] = dict.fromkeys(gold["alerts_by_rule"], "boom")


def _no_alerts(rec: dict) -> None:
    rec["financial_scoring"]["total_alerts"] = 0


MUTATIONS = {
    "silver_rows_0": (C360_BATCH, _silver_zero, "layer_rows"),
    "gold_rows_and_bytes_0": (C360_BATCH, _gold_zero, "layer_rows"),
    "every_answer_empty": (C360_BATCH, _answers_empty, "query_answers"),
    "scale_ratio_0": (C360_BATCH, _ratio_zero, "scale_ratio"),
    "every_rule_errored": (AML_BATCH, _rules_errored, "aml_rules"),
    "zero_alerts": (AML_BATCH, _no_alerts, "aml_rules"),
}


@pytest.mark.parametrize("name", sorted(MUTATIONS))
def test_mutated_records_fail(name: str) -> None:
    """SPEC EVD-1 acceptance: each mutation FAILS on its own gate."""
    run, mutate, gate = MUTATIONS[name]
    rec = sr.load_record(run)
    mutate(rec)
    v = V.verdict_from_record(rec)
    assert v.status == "FAILED", v.reasons
    assert v.gates[gate] == "FAIL"
    assert f"Gate '{gate}' FAILED" in v.reasons
    assert not V.passed(rec)


@pytest.mark.parametrize("run", [C360_BATCH, AML_BATCH, AML_CONT, C360_CONT])
def test_unmutated_records_pass(run: str) -> None:
    rec = sr.load_record(run)
    v = V.verdict_from_record(rec)
    assert v.status == "PASSED", v.reasons
    for gate, outcome in v.gates.items():
        assert outcome == "PASS", gate
    assert v.qualifiers[V.LAYER_ROWS_UNMEASURED] == []
    assert V.passed(rec)


