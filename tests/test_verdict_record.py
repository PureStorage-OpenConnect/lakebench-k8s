RECORD_GATES = {"layer_rows", "aml_rules", "scale_ratio", "query_answers"}
EXPECTED = json.loads((ROOT / "tests" / "expected" / "verdict_recomputed.json").read_text())


@pytest.mark.parametrize("run", sorted(EXPECTED["records"]))
def test_pinned_records_recompute_as_expected(run: str) -> None:
    """Every pinned record's verdict from the record alone, and the gates
    that fail it. A stored pass that reads failed here is listed in
    UPGRADING; the expected file is never regenerated by code."""
    want = EXPECTED["records"][run]
    rec = sr.load_record(run)
    v = V.verdict_from_record(rec)
    assert v.status == want["status"], v.reasons
    failing = sorted(g for g, o in v.gates.items() if o == "FAIL" and g in RECORD_GATES)
    assert failing == want["failing_gates"]
    assert v.qualifiers.get(V.LAYER_ROWS_UNMEASURED) == want["layer_rows_unmeasured"]
    assert V.passed(rec) is (want["status"] == "PASSED")


def test_only_the_listed_stored_passes_flip() -> None:
    """A stored pass (PASSED, or success on a record with no verdict block)
    that recomputes as failed is one of the three listed records."""
    flips = []
    for run in sr.record_ids():
        rec = sr.load_record(run)
        if V.stored_passed(rec) and not V.passed(rec):
            flips.append(run)
    assert flips == sorted(EXPECTED["stored_pass_now_failed"])


