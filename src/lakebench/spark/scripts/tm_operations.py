def ops_summary(as_of, params, recon_rows, counts):
    """The operations pack, computed from the grouped rows read_back
    collected (no further Spark actions)."""
    dg = [r for r in counts["_dg"] if r["is_customer"]]
    cg = counts["_cg"]

    def s(rows, pred):
        return sum(int(r["n"]) for r in rows if pred(r))

    def decided(r):
        return r["disposition"] in WORKED_DISPOSITIONS and r["decided"]

    per_rule = {}
    for rid in sorted({r["rule_id"] for r in dg}):
        rr = [r for r in dg if r["rule_id"] == rid]
        n = s(rr, lambda r: True)
        dec = s(rr, decided)
        prod = s(rr, lambda r: decided(r) and (r["disposition"] == DISP_ESCALATED or r["on_sar"]))
        per_rule[rid] = {
            "alerts": n,
            "escalated": s(rr, lambda r: r["disposition"] == DISP_ESCALATED),
            "productive_rate": (prod / dec) if dec else None,
            "sar_conversion": (s(rr, lambda r: r["on_sar"]) / n) if n else None,
        }
    aging = {name: 0 for _, _, name in AGING_BUCKETS}
    for r in counts["_dg"]:
        if r["queue_status"] == "open":
            aging[r["aging_bucket"]] += int(r["n"])
    l1 = [r for r in dg if r["l1_decided"]]
    n_l1 = s(l1, lambda r: True)
    n_qa = s(l1, lambda r: r["qa_sampled"])
    by_priority = {}
    for r in dg:
        by_priority[r["triage_priority"]] = by_priority.get(r["triage_priority"], 0) + int(r["n"])
    by_disp = {}
    for r in counts["_dg"]:
        by_disp[r["disposition"]] = by_disp.get(r["disposition"], 0) + int(r["n"])
    filing = []
    for r in cg:
        if r["determination_to_filing_days"] is not None:
            filing.extend([int(r["determination_to_filing_days"])] * int(r["n"]))
    filing.sort()
    by_status, by_type, by_limit = {}, {}, {}
    for r in cg:
        by_status[r["case_status"]] = by_status.get(r["case_status"], 0) + int(r["n"])
        by_type[r["case_type"]] = by_type.get(r["case_type"], 0) + int(r["n"])
    sar = [r for r in cg if r["sar_decision"] == "sar_filed"]
    for r in sar:
        k = r["regulatory_limit"] or "unknown"
        cur = by_limit.setdefault(k, {"filed": 0, "late": 0})
        cur["filed"] += int(r["n"])
        cur["late"] += int(r["n"]) if r["filed_late"] else 0

    def pct(xs, q):
        if not xs:
            return None
        return xs[min(len(xs) - 1, int(q * (len(xs) - 1) + 0.5))]

    sim_keys = [k for k in sorted(params) if k != "counterparty_scenarios"]
    return {
        "as_of_date": as_of.isoformat(),
        "simulation": {
            "note": "dispositions simulated from datagen ground truth",
            **{k: params[k] for k in sim_keys},
            "counterparty_scenarios": list(params.get("counterparty_scenarios") or ()),
        },
        "reconciliation": {f"{s_}.{i}": v for s_, i, _, v, _ in recon_rows},
        "funnel": {
            "payments": counts["source"],
            "monitored": counts["monitored"],
            "alerts": counts["customer_alerts"],
            "escalated": counts["escalated"],
            "cases": counts["alert_cases"],
            "sars": counts["alert_sars"],
        },
        "alerts_total": counts["alerts"],
        "alerts_out_of_scope": counts["noncustomer_alerts"],
        "alerts_noncustomer_undeclared": counts["noncustomer_undeclared"],
        "alerts_withdrawn_carried": counts["withdrawn_alerts"],
        "alerts_over_capacity": counts["over_capacity"],
        "alerts_by_disposition": by_disp,
        "l1_decided": n_l1,
        "l1_escalation_rate": (
            s(l1, lambda r: r["disposition"] == DISP_ESCALATED) / n_l1 if n_l1 else None
        ),
        "alert_sla_breaches": s(l1, lambda r: r["sla_breached"]),
        "qa_sample": n_qa,
        "qa_disagreement_rate": (s(l1, lambda r: bool(r["qa_disagrees"])) / n_qa) if n_qa else None,
        "alerts_by_priority": by_priority,
        "alert_aging_open": aging,
        "cases_by_status": by_status,
        "cases_by_type": by_type,
        "open_cases": counts["cases"] - by_status.get("closed", 0),
        "open_cases_over_60_days": s(
            cg, lambda r: r["case_status"] != "closed" and bool(r["opened_60"])
        ),
        "sars_filed": counts["sars"],
        "sars_by_limit": by_limit,
        "sars_no_suspect": s(sar, lambda r: r["suspect_identified"] is False),
        "continuing_sars_over_120_days": s(sar, lambda r: bool(r["over_120"])),
        "filing_days_median": pct(filing, 0.5),
        "filing_days_p95": pct(filing, 0.95),
        "filed_over_30_days_pct": (
            (sum(1 for x in filing if x > FILING_DEADLINE_DAYS) / len(filing)) if filing else None
        ),
        "filed_late": s(sar, lambda r: bool(r["filed_late"])),
        "continuing_reviews_due": counts["reviews_due"],
        "continuing_reviews_opened": counts["reviews_opened"],
        "continuing_reviews_folded": counts["reviews_folded"],
        "continuing_reviews_deferred": counts["reviews_deferred"],
        "continuing_reviews_superseded": counts["reviews_superseded"],
        "scenarios": per_rule,
    }


