"""Transaction-monitoring operations layer on top of gold.alerts (GOALS P10).

Runs after detection in the AML gold stage (gold_finalize_financial in batch,
gold_refresh_financial in continuous) and turns an alert table into the shape
of a bank's TM operation:

- Stage 1, monitoring completeness: ``gold.tm_reconciliation`` accounts for
  every source payment as monitored or excluded for a stated reason, lists
  data-quality rule failures, and carries the cycle funnel (payments ->
  monitored -> alerts -> escalated -> cases -> SARs). One set of rows per
  cycle (batch) or per operations tick (continuous), appended.
  ``gold.scenario_coverage`` is the scenario-to-typology matrix.
- Stage 6, L1 triage: ``gold.alert_dispositions``. Priority is scenario
  weight x CRR tier. Each alert is closed (``closed_nfa``) or ``escalated``
  by a simulated analyst, ``attached`` to the customer's open case
  (suppression), or ``pending_l1`` while it waits. A QA sample is re-reviewed
  and the disagreement rate kept.
- Stage 7, L2 cases: ``gold.cases``, keyed on the customer, at most one open
  case per customer, pulling every open alert plus the lookback window of
  activity.
- Stage 8, SAR decision: ``sar_filed`` / ``no_sar`` with the clocks:
  alert-to-decision aging against a policy SLA; determination-to-filing
  against 31 CFR 1020.320 (30 days, 60 when no suspect is identified); and
  for continuing activity the FinCEN limit of 120 days after the prior SAR,
  with the review opened 90 days after each SAR.

Dispositions are SIMULATED from ground truth. An alert is truly suspicious
when it touches a planted (non-control) typology transaction in the datagen
manifest; the L1 analyst decides correctly with probability
``analyst_accuracy`` and the L2 investigator with ``investigator_accuracy``.
Every random draw is a hash of (seed, draw name, a stable key), not of
arrival order.

Alert identity and history. An alert keeps the identity it was first seen
with (``alert_key``). The next cycle reads the previous cycle's dispositions
and matches each alert to it: the same content (rule, entity, time, related
payments) first, else the same rule on the same customer whose pattern
extended forward by at most ``EXTENSION_MATCH_DAYS`` (a window that grew as
the corpus grew). A matched alert keeps its key, generated date, truth and
priority as first seen; an alert that detection no longer emits is carried
forward (``in_current_detection`` false) rather than erased; an alert first
seen this cycle whose last payment predates the previous cycle is dated on
this cycle's as-of date, the first day the overnight run could have raised
it. The day-by-day replay is causal (a decision on day d depends only on
alerts generated by day d) and its inputs for every already-seen alert are
frozen, so recomputing it reproduces every decision up to the previous
as-of date exactly. The ``history_stable`` invariant checks that on the
written tables against the previous cycle's snapshot.

Time. The unit of work is the business day. An alert is generated the day
after its last contributing payment (the overnight scenario run), and the
workflow is replayed day by day up to the cycle's as-of date (the day after
the newest payment in the silver snapshot). Decisions dated after the as-of
date have not happened yet: those alerts and cases are the open backlog.

Continuous behaviour. gold_refresh runs this layer every
``continuous_interval_seconds`` (not every tick: at scale 10 one pass costs
minutes). Silver is read at one pinned snapshot, taken before the source
files are counted, so payments datagen wrote after the snapshot count as
``in_flight`` and never as a negative.

Workflow invariants (P10.2) are checked against the tables as written, read
back, and logged as ``[tm-invariant]`` lines; ``[tm-status]`` says whether
the layer ran and why not; a ``[tm-ops]`` JSON line carries the operations
summary for the scorecard.
"""

