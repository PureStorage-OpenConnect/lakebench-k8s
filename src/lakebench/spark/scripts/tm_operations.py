_MICROS_PER_DAY = 86_400 * 1_000_000


def _ts(a):
    return a["alert_ts"] if a["alert_ts"] is not None else -1


def match_alerts(current, prior, prev_as_of, as_of, cycle):
    """This cycle's alerts on one customer, with their identity carried.

    ``current``: dicts alert_id, alert_key, content_hash, rule_id, alert_ts
    (epoch microseconds: a Python datetime would take the executor's local
    zone), generated_date (the day after the last payment), truth, triage_priority,
    priority_score, scenario_weight. ``prior``: the previous cycle's rows for
    the customer, same keys plus first_seen_cycle and first_seen_as_of.

    Returns alert dicts for :func:`simulate_customer`: matched alerts keep the
    prior key and frozen attributes, withdrawn prior alerts are carried with
    ``in_current_detection`` false, and new alerts are dated no earlier than
    the first cycle that could have raised them.
    """
    out = []
    # Every prior key is taken, matched or not: a new alert must never be
    # handed the key of a prior alert carried as withdrawn.
    used = {p["alert_key"] for p in prior}
    by_content = {}
    for p in sorted(prior, key=lambda x: (_ts(x), x["alert_key"])):
        by_content.setdefault(p["content_hash"], []).append(p)

    def carry(p, cur):
        a = dict(p)
        a["alert_id"] = cur["alert_id"] if cur is not None else p["alert_id"]
        a["in_current_detection"] = cur is not None
        if cur is not None:
            # The alert as detection emits it now; the workflow attributes
            # stay as first seen.
            a["alert_ts"] = cur["alert_ts"]
            a["content_hash"] = cur["content_hash"]
        used.add(a["alert_key"])
        out.append(a)

    cur_sorted = sorted(current, key=lambda x: (_ts(x), x["content_hash"], x["alert_key"]))
    unmatched = []
    for c in cur_sorted:
        same = by_content.get(c["content_hash"])
        if same:
            carry(same.pop(0), c)
        else:
            unmatched.append(c)
    remaining = {}
    for lst in by_content.values():
        for p in lst:
            remaining.setdefault(p["rule_id"], []).append(p)
    window = EXTENSION_MATCH_DAYS * _MICROS_PER_DAY
    for c in unmatched:
        cands = remaining.get(c["rule_id"]) or []
        best = None
        for p in cands:
            if p["alert_ts"] is None or c["alert_ts"] is None:
                continue
            # The earliest prior this alert could have grown from: with
            # current alerts taken in time order this pairs grown windows in
            # order instead of letting an early alert take a later one's key.
            if p["alert_ts"] <= c["alert_ts"] <= p["alert_ts"] + window:
                if best is None or p["alert_ts"] < best["alert_ts"]:
                    best = p
        if best is not None:
            cands.remove(best)
            carry(best, c)
            continue
        a = dict(c)
        raw = c["generated_date"]
        if prev_as_of is not None and raw <= prev_as_of:
            # Not raised by the previous cycle although its payments were
            # already there: the first run that could raise it is this one.
            a["generated_date"] = as_of
        key = a["alert_key"]
        while key in used:
            key += "+"
        a["alert_key"] = key
        used.add(key)
        a["first_seen_cycle"] = cycle
        a["first_seen_as_of"] = as_of
        a["in_current_detection"] = True
        out.append(a)
    for lst in remaining.values():
        for p in lst:
            carry(p, None)
    return out


