def bootstrap_tm_tables(spark) -> None:
    """Create the TM tables (and their namespaces, which the Hive catalog does
    not pre-create). A table left by an earlier build that lacks a column is
    upgraded in place with a nullable ADD COLUMNS."""
    from common import ensure_column, ensure_namespaces_for_ddl

    ensure_namespaces_for_ddl(spark, CATALOG, [ddl for _, ddl in TM_DDLS])
    for (name, ddl), table in zip(TM_DDLS, TM_TABLES):  # noqa: B905 -- Python 3.9 image
        spark.sql(ddl)
        fq = f"{CATALOG}.{table}"
        existing = set(spark.table(fq).columns)
        for col_name, sql_type in ddl_columns(ddl):
            if col_name not in existing:
                ensure_column(spark, fq, col_name, sql_type)
        log(f"Bootstrapped gold.{name}")


