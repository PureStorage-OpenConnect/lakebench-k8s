def evaluate_invariants(counts: dict) -> list[tuple[str, str, str]]:
    """``counts`` from :func:`read_back`. Returns (name, status, detail)."""
    out = []

    def check(name, ok, detail):
        out.append((name, "pass" if ok else "fail", detail))

    custs = counts.get("customers")
    check(
        "monitored_population",
        bool(custs) and counts["monitored"] > 0,
        f"{custs} customers of the reporting FI, {counts['monitored']} monitored payments",
    )
    src = counts.get("source")
    mon, exc = counts["monitored"], counts["excluded"]
    if src is None:
        out.append(
            (
                "reconciliation",
                "unchecked",
                "source payment count unavailable (listing the raw files failed); "
                "completeness unproven",
            )
        )
    else:
        # A negative item (silver holding more than the source, so in_flight
        # below zero) is a duplication, not a balanced ledger.
        neg = counts.get("negative_items") or []
        check(
            "reconciliation",
            mon + exc == src and not neg,
            f"monitored {mon} + excluded {exc} = {mon + exc} vs source {src}"
            + (f"; negative: {', '.join(neg)}" if neg else ""),
        )
    alerts, disp = counts["alerts"], counts["dispositions"]
    check(
        "every_alert_dispositioned",
        alerts == disp,
        f"alerts {alerts}, disposition rows for them {disp}",
    )
    rows, keys = counts.get("disposition_rows"), counts.get("distinct_alert_keys")
    if rows is not None and keys is not None:
        check(
            "one_row_per_alert_identity",
            rows == keys,
            f"{rows} disposition rows, {keys} distinct alert identities",
        )
    nulls = counts.get("null_dispositions", 0)
    check("no_null_disposition", nulls == 0, f"{nulls} disposition rows with no disposition")
    und = counts.get("noncustomer_undeclared", 0)
    check(
        "noncustomer_alerts_declared",
        und == 0,
        f"{und} alerts on non-customers from scenarios not declared customer-and-counterparty"
        f" ({counts.get('noncustomer_alerts', 0)} non-customer alerts in all)",
    )
    ca, esc = counts["customer_alerts"], counts["escalated"]
    check("escalated_le_alerts", esc <= ca, f"escalated {esc} <= customer alerts {ca}")
    ac = counts["alert_cases"]
    check("cases_le_escalated", ac <= esc, f"alert-driven cases {ac} <= escalated {esc}")
    sars, cases = counts["sars"], counts["cases"]
    check("sars_le_cases", sars <= cases, f"SARs {sars} <= cases {cases}")
    mo = counts["max_open_per_customer"]
    check("one_open_case_per_customer", mo <= 1, f"most open cases on one customer: {mo}")
    funnel = [
        ("payments", src if src is not None else counts["silver"]),
        ("monitored", mon),
        ("alerts", ca),
        ("escalated", esc),
        ("cases", ac),
        ("sars", counts["alert_sars"]),
    ]
    # No zip(strict=...): the Spark image runs Python 3.9.
    bad = [
        f"{funnel[i][0]}={funnel[i][1]} < {funnel[i + 1][0]}={funnel[i + 1][1]}"
        for i in range(len(funnel) - 1)
        if funnel[i + 1][1] > funnel[i][1]
    ]
    check(
        "funnel_monotone",
        not bad,
        "; ".join(bad) or " >= ".join(f"{k} {v}" for k, v in funnel),
    )
    miss = counts["reviews_missing"]
    check(
        "continuing_review_fires",
        miss == 0,
        f"{miss} SARs past their 90-day review date with no review "
        f"({counts['reviews_due']} due, {counts.get('reviews_deferred', 0)} deferred behind "
        "a case waiting to file)",
    )
    folded = counts.get("reviews_folded_into_determined", 0)
    check(
        "review_not_folded_into_determined",
        folded == 0,
        f"{folded} reviews credited to a case already determined before the review was due",
    )
    if counts.get("history_checked"):
        changed = counts.get("history_changed", 0)
        check(
            "history_stable",
            changed == 0,
            f"{changed} decisions made by {counts.get('prev_as_of')} differ from the previous "
            f"cycle ({counts.get('history_compared', 0)} compared)",
        )
    return out


def _flag(c):
    from pyspark.sql.functions import lit, when

    return when(c, lit(1)).otherwise(lit(0))


def read_back(
    spark, run_id, as_of, prior_disp=None, prior_cases=None, prev_as_of=None, rerun=False
):
    """Everything the invariants, the funnel rows and the operations summary
    need, from the written tables in a handful of actions: one grouped
    collect per table, the open-case maximum, the folded-review check, and
    the history comparison when there is a previous cycle."""
    from pyspark.sql.functions import broadcast, col, count, lit, when
    from pyspark.sql.functions import max as max_

    d = spark.table(f"{CATALOG}.{GOLD_DISPOSITIONS}").where(col("run_id") == lit(run_id))
    cases = spark.table(f"{CATALOG}.{GOLD_CASES}").where(col("run_id") == lit(run_id))
    sar_cases = cases.where(col("sar_decision") == lit("sar_filed")).select(
        "case_id", lit(True).alias("_sar")
    )
    bucket = None
    for lo, hi, name in AGING_BUCKETS:
        cond = col("aging_days") >= lit(lo)
        if hi is not None:
            cond = cond & (col("aging_days") <= lit(hi))
        bucket = when(cond, lit(name)) if bucket is None else bucket.when(cond, lit(name))
    dg = (
        d.join(broadcast(sar_cases), "case_id", "left")
        .groupBy(
            "rule_id",
            "is_customer",
            "declared_counterparty",
            "in_current_detection",
            "disposition",
            "queue_status",
            "triage_priority",
            bucket.otherwise(lit("0-30")).alias("aging_bucket"),
            "sla_breached",
            col("l1_decision_date").isNotNull().alias("l1_decided"),
            col("decision_date").isNotNull().alias("decided"),
            col("_sar").isNotNull().alias("on_sar"),
            "qa_sampled",
            "qa_disagrees",
        )
        .agg(count(lit(1)).alias("n"))
        .collect()
    )
    cg = (
        cases.groupBy(
            "case_type",
            "case_status",
            "sar_decision",
            "suspect_identified",
            "regulatory_limit",
            "filed_late",
            "continuing_review_status",
            (col("continuing_review_due_date") <= lit(as_of)).alias("review_due"),
            col("continuing_review_case_id").isNull().alias("review_missing"),
            (col("opened_date") <= lit(as_of - timedelta(days=60))).alias("opened_60"),
            "determination_to_filing_days",
            (col("days_since_prior_sar") > lit(CONTINUING_FILING_LIMIT_DAYS)).alias("over_120"),
        )
        .agg(count(lit(1)).alias("n"))
        .collect()
    )
    mo = (
        cases.where(col("case_status") != lit("closed"))
        .groupBy("customer_id")
        .count()
        .agg(max_("count").alias("m"))
        .collect()[0]["m"]
    )
    # A folded review is credited to a case that was still undetermined when
    # the review fell due.
    parents = cases.where(col("continuing_review_status") == lit("folded")).select(
        col("continuing_review_case_id").alias("case_id"),
        col("continuing_review_due_date").alias("_due"),
    )
    folded_bad = (
        parents.join(cases.select("case_id", "determination_date"), "case_id", "left")
        .where(col("determination_date").isNotNull() & (col("determination_date") < col("_due")))
        .count()
    )
    alerts = spark.table(f"{CATALOG}.{GOLD_ALERTS}").where(col("run_id") == lit(run_id)).count()
    distinct_keys = d.select("alert_key").distinct().count()

    def s(rows, pred):
        return sum(int(r["n"]) for r in rows if pred(r))

    cust = [r for r in dg if r["is_customer"]]
    c_alert = [r for r in cg if r["case_type"] == "alert_escalation"]
    sar = [r for r in cg if r["sar_decision"] == "sar_filed"]
    counts = {
        "alerts": int(alerts),
        "dispositions": s(dg, lambda r: r["in_current_detection"]),
        "disposition_rows": s(dg, lambda r: True),
        "distinct_alert_keys": int(distinct_keys),
        "null_dispositions": s(dg, lambda r: r["disposition"] is None),
        "noncustomer_alerts": s(dg, lambda r: not r["is_customer"]),
        "noncustomer_undeclared": s(
            dg, lambda r: not r["is_customer"] and not r["declared_counterparty"]
        ),
        "withdrawn_alerts": s(dg, lambda r: not r["in_current_detection"]),
        "over_capacity": s(dg, lambda r: r["disposition"] == DISP_OVER_CAPACITY),
        "customer_alerts": s(cust, lambda r: True),
        "escalated": s(cust, lambda r: r["disposition"] == DISP_ESCALATED),
        "cases": s(cg, lambda r: True),
        "alert_cases": s(c_alert, lambda r: True),
        "review_cases": s(cg, lambda r: r["case_type"] != "alert_escalation"),
        "sars": s(sar, lambda r: True),
        "alert_sars": s(sar, lambda r: r["case_type"] == "alert_escalation"),
        "review_sars": s(sar, lambda r: r["case_type"] != "alert_escalation"),
        "max_open_per_customer": int(mo or 0),
        "reviews_due": s(sar, lambda r: bool(r["review_due"])),
        "reviews_missing": s(
            sar,
            lambda r: (
                bool(r["review_due"])
                and r["review_missing"]
                and r["continuing_review_status"] != "deferred"
            ),
        ),
        "reviews_deferred": s(sar, lambda r: r["continuing_review_status"] == "deferred"),
        "reviews_superseded": s(
            sar, lambda r: r["continuing_review_status"] == "superseded_by_sar"
        ),
        "reviews_opened": s(sar, lambda r: r["continuing_review_status"] == "opened"),
        "reviews_folded": s(sar, lambda r: r["continuing_review_status"] == "folded"),
        "reviews_folded_into_determined": int(folded_bad),
        "_dg": dg,
        "_cg": cg,
    }
    counts.update(
        _history_check(spark, run_id, prior_disp, prior_cases, prev_as_of, rerun)
        if prior_disp is not None and prev_as_of is not None
        else {"history_checked": False}
    )
    return counts


def _history_check(spark, run_id, prior_disp, prior_cases, prev_as_of, rerun=False):
    """Decisions made by the previous as-of date, compared with this cycle's
    tables: a changed disposition, case, decision date, determination or
    filing is history rewritten."""
    from pyspark.sql.functions import coalesce, col, lit

    same = lambda a, b: coalesce(col(a) == col(b), col(a).isNull() & col(b).isNull())  # noqa: E731
    prev = lit(prev_as_of)
    worked = col("disposition").isin(*WORKED_DISPOSITIONS)
    if rerun:
        # A rerun's prior tables also hold decisions made after the previous
        # as-of date, which may legitimately differ: compare only decisions
        # dated by then (an undated attachment is not compared).
        worked = worked & ((col("decision_date") <= prev) | (col("l1_decision_date") <= prev))
    pd_ = prior_disp.where(worked).select(
        "alert_key",
        col("disposition").alias("p_disp"),
        col("case_id").alias("p_case"),
        col("decision_date").alias("p_dec"),
    )
    nd = spark.table(f"{CATALOG}.{GOLD_DISPOSITIONS}").where(col("run_id") == lit(run_id))
    nd = nd.select(
        "alert_key",
        col("disposition").alias("n_disp"),
        col("case_id").alias("n_case"),
        col("decision_date").alias("n_dec"),
        lit(True).alias("_present"),
    )
    j = pd_.join(nd, "alert_key", "left")
    changed_d = ~(
        col("_present").isNotNull()
        & same("p_disp", "n_disp")
        & same("p_case", "n_case")
        & (col("p_dec").isNull() | (col("p_dec") > prev) | same("p_dec", "n_dec"))
    )
    dc = j.select(_flag(changed_d).alias("c")).groupBy().sum("c").collect()[0][0] or 0
    dn = pd_.count()
    cn = cc = 0
    if prior_cases is not None:
        pc = prior_cases.where(col("opened_date") <= prev).select(
            "case_id",
            col("determination").alias("p_det"),
            col("determination_date").alias("p_dd"),
            col("sar_decision").alias("p_sar"),
            col("filing_date").alias("p_fd"),
        )
        nc = spark.table(f"{CATALOG}.{GOLD_CASES}").where(col("run_id") == lit(run_id))
        nc = nc.select(
            "case_id",
            col("determination").alias("n_det"),
            col("determination_date").alias("n_dd"),
            col("sar_decision").alias("n_sar"),
            col("filing_date").alias("n_fd"),
            lit(True).alias("_present"),
        )
        jc = pc.join(nc, "case_id", "left")
        changed_c = ~(
            col("_present").isNotNull()
            & (
                col("p_dd").isNull()
                | (col("p_dd") > prev)
                | (same("p_det", "n_det") & same("p_dd", "n_dd"))
            )
            & (
                col("p_fd").isNull()
                | (col("p_fd") > prev)
                | (same("p_sar", "n_sar") & same("p_fd", "n_fd"))
            )
        )
        cc = jc.select(_flag(changed_c).alias("c")).groupBy().sum("c").collect()[0][0] or 0
        cn = pc.count()
    return {
        "history_checked": True,
        "history_changed": int(dc) + int(cc),
        "history_compared": int(dn) + int(cn),
        "prev_as_of": prev_as_of.isoformat(),
    }


