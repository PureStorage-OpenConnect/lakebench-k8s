def current_snapshot_id(spark, fq_table):
    """The table's newest snapshot id, or None (empty, or not Iceberg)."""
    try:
        rows = spark.sql(
            f"SELECT snapshot_id FROM {fq_table}.snapshots ORDER BY committed_at DESC LIMIT 1"
        ).collect()
    except Exception as e:  # noqa: BLE001
        log(f"[tm] snapshot of {fq_table} unavailable: {one_line(e)}")
        return None
    return int(rows[0][0]) if rows else None


def read_at_snapshot(spark, fq_table, snapshot_id):
    """The table as of one snapshot, so every action reads the same data."""
    if snapshot_id is None:
        return spark.table(fq_table)
    return spark.sql(f"SELECT * FROM {fq_table} VERSION AS OF {int(snapshot_id)}")


