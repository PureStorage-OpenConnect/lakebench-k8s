# Event order within one day: a case closing frees the customer before a
# review opens, reviews and L1 decisions open cases before the day's new
# alerts arrive, so a same-day arrival attaches to a case opened that day.
_EV_CLOSE, _EV_DETERMINE, _EV_REVIEW, _EV_L1, _EV_ARRIVE = range(5)


def simulate_customer(customer_id, crr_tier, alerts, params, as_of):
    """Replay one customer's alerts through L1, L2 and SAR filing.

    ``alerts``: dicts with alert_id, alert_key, rule_id, generated_date,
    truth, triage_priority, priority_score (other keys pass through). ``as_of``:
    the cycle's business date; nothing dated later has happened.

    Returns ``(dispositions, cases)``: lists of dicts, one per alert and one
    per case.
    """
    seed = int(params["seed"])
    l1_acc = float(params["analyst_accuracy"])
    l2_acc = float(params["investigator_accuracy"])
    qa_rate = float(params["qa_sample_rate"])
    sla = int(params["alert_sla_days"])
    lookback = int(params["lookback_months"])
    late_rate = float(params["late_filing_rate"])
    no_suspect_rate = float(params.get("no_suspect_rate", 0.0))

    st = {}  # alert_key -> mutable state
    pending = {}  # alert keys awaiting L1, in arrival order (dict as ordered set)
    cases = []
    open_case = [None]
    deferred_reviews = []  # parents whose review waits for a determined case to close
    events = []
    seq = [0]
    by_id = {}

    def push(day, kind, ref):
        seq[0] += 1
        heapq.heappush(events, (day, kind, seq[0], ref))

    for a in sorted(alerts, key=lambda x: (x["generated_date"], x["alert_key"])):
        st[a["alert_key"]] = {
            "a": a,
            "disposition": None,
            "l1_date": None,
            "case": None,
            "decision_date": None,
            "correct": None,
        }
        push(a["generated_date"], _EV_ARRIVE, a["alert_key"])

    def link(s, case, disposition, day):
        s["disposition"] = disposition
        s["case"] = case
        case["alert_keys"].append(s["a"]["alert_key"])
        if case["determination_date"] is not None:
            # Determination already made (SAR being filed): the alert is
            # reviewed as continuing activity on attachment.
            s["decision_date"] = max(day, case["determination_date"])

    def open_new_case(day, case_type, parent=None):
        cid = case_id_for(customer_id, day, case_type)
        continuing = case_type == "continuing_activity"
        case = {
            "case_id": cid,
            "case_type": case_type,
            "parent": parent,
            "opened_date": day,
            "alert_keys": [],
            "escalated": 0,
            "determination": None,
            "determination_date": None,
            "sar_decision": None,
            "filing_date": None,
            "filing_deadline": None,
            "regulatory_limit": None,
            "close_date": None,
            "review_due": None,
            "review_case_id": None,
            "review_status": None,
            # The subject of a continuing-activity review is the SAR's
            # subject; a new case may not have identified one.
            "suspect": continuing or draw(seed, "no_suspect", cid) >= no_suspect_rate,
            "truth": False,
            "review_since": parent["filing_date"] if parent else None,
        }
        cases.append(case)
        by_id[cid] = case
        open_case[0] = case
        # Suppression and case scope: every alert still waiting for L1 on
        # this customer joins the case.
        for k in list(pending):
            link(st[k], case, DISP_ATTACHED, day)
        pending.clear()
        span = REVIEW_INVESTIGATION_DAYS if continuing else INVESTIGATION_DAYS
        inv = draw_int(seed, "investigation", cid, *span)
        push(day + timedelta(days=inv), _EV_DETERMINE, cid)
        return case

    def open_review(day, parents):
        rc = open_new_case(day, "continuing_activity", parent=parents[0])
        for p in parents:
            p["review_case_id"] = rc["case_id"]
            p["review_status"] = "opened"

    while events:
        day, kind, _, ref = heapq.heappop(events)
        if day > as_of:
            break
        if kind == _EV_ARRIVE:
            s = st[ref]
            if open_case[0] is not None:
                link(s, open_case[0], DISP_ATTACHED, day)
            else:
                lo, hi = L1_TURNAROUND_DAYS[s["a"]["triage_priority"]]
                pending[ref] = True
                push(
                    day + timedelta(days=draw_int(seed, "l1_turnaround", ref, lo, hi)), _EV_L1, ref
                )
        elif kind == _EV_L1:
            s = st[ref]
            if ref not in pending:
                continue  # attached to a case before its turn came
            del pending[ref]
            s["l1_date"] = day
            correct = draw(seed, "l1", ref) < l1_acc
            truth = bool(s["a"]["truth"])
            s["correct"] = correct
            if truth == correct:  # escalate: right on a true alert, wrong on a false one
                case = open_case[0]
                if case is None:
                    case = open_new_case(day, "alert_escalation")
                link(s, case, DISP_ESCALATED, day)
                case["escalated"] += 1
            else:
                s["disposition"] = DISP_CLOSED
                s["decision_date"] = day
        elif kind == _EV_DETERMINE:
            case = by_id[ref]
            members = [st[k] for k in case["alert_keys"]]
            continuing = case["case_type"] == "continuing_activity"
            if continuing:
                since = case["review_since"]
                truth = any(
                    x["a"]["truth"] and since < x["a"]["generated_date"] <= day for x in st.values()
                )
            else:
                truth = any(m["a"]["truth"] for m in members)
            case["truth"] = truth
            correct = draw(seed, "l2", case["case_id"]) < l2_acc
            suspicious = truth == correct
            case["determination_date"] = day
            for m in members:
                m["decision_date"] = day
            if suspicious:
                case["determination"] = "suspicious"
                deadline = filing_deadline(day, case["suspect"])
                limit = "30_day" if case["suspect"] else "60_day_no_suspect"
                if continuing:
                    prior_sar = case["parent"]["filing_date"]
                    cap = prior_sar + timedelta(days=CONTINUING_FILING_LIMIT_DAYS)
                    if cap < deadline:
                        deadline, limit = cap, "120_day_continuing"
                case["filing_deadline"] = deadline
                case["regulatory_limit"] = limit
                room = (deadline - day).days
                if draw(seed, "late_filing", case["case_id"]) < late_rate:
                    lag = room + draw_int(
                        seed, "filing_days", case["case_id"], *LATE_FILING_EXTRA_DAYS
                    )
                else:
                    # Inside the deadline; a determination made with under
                    # two days left files late, and says so.
                    lag = draw_int(seed, "filing_days", case["case_id"], 2, max(2, room - 2))
                push(day + timedelta(days=lag), _EV_CLOSE, case["case_id"])
            else:
                case["determination"] = "not_suspicious"
                case["sar_decision"] = "no_sar"
                case["close_date"] = day
                open_case[0] = None
        elif kind == _EV_CLOSE:
            case = by_id[ref]
            case["sar_decision"] = "sar_filed"
            case["filing_date"] = day
            case["close_date"] = day
            case["review_due"] = day + timedelta(days=CONTINUING_REVIEW_DAYS)
            open_case[0] = None
            push(case["review_due"], _EV_REVIEW, case["case_id"])
            if deferred_reviews:
                # Reviews that fell due while this case was waiting to file:
                # the SAR it just filed covers the customer's activity to
                # date, so it is the continuing-activity filing for them.
                for p in deferred_reviews:
                    p["review_case_id"] = case["case_id"]
                    p["review_status"] = "superseded_by_sar"
                deferred_reviews.clear()
        elif kind == _EV_REVIEW:
            parent = by_id[ref]
            oc = open_case[0]
            if oc is None:
                open_review(day, [parent])
            elif oc["determination_date"] is None:
                # The customer is under investigation: the review is folded
                # into the open case, whose determination covers it.
                parent["review_case_id"] = oc["case_id"]
                parent["review_status"] = "folded"
            else:
                # The open case is already determined and only waiting to
                # file; it reviews nothing new. Its SAR, once filed, is the
                # continuing-activity filing (see _EV_CLOSE).
                parent["review_status"] = "deferred"
                deferred_reviews.append(parent)

    dispositions = []
    for k, s in st.items():
        a = s["a"]
        decided = s["decision_date"]
        aging = max(0, ((decided or as_of) - a["generated_date"]).days)
        qa_sampled = s["l1_date"] is not None and draw(seed, "qa_pick", k) < qa_rate
        qa_disp = None
        qa_dis = None
        if qa_sampled:
            qa_correct = draw(seed, "qa", k) < l2_acc
            qa_disp = DISP_ESCALATED if bool(a["truth"]) == qa_correct else DISP_CLOSED
            l1_disp = DISP_ESCALATED if s["disposition"] == DISP_ESCALATED else DISP_CLOSED
            qa_dis = qa_disp != l1_disp
        row = {x: a.get(x) for x in _PASS_THROUGH if x in a}
        row.update(
            {
                "alert_id": a["alert_id"],
                "alert_key": k,
                "l1_decision_date": s["l1_date"],
                "disposition": s["disposition"] or DISP_PENDING,
                "queue_status": "closed" if decided is not None else "open",
                "case_id": s["case"]["case_id"] if s["case"] else None,
                "decision_date": decided,
                "aging_days": aging,
                "sla_breached": aging > sla,
                "analyst_correct": s["correct"],
                "qa_sampled": qa_sampled,
                "qa_disposition": qa_disp,
                "qa_disagrees": qa_dis,
            }
        )
        dispositions.append(row)

    out_cases = []
    for c in cases:
        members = [st[k]["a"] for k in c["alert_keys"]]
        first = min((m["generated_date"] for m in members), default=None)
        rank = max((PRIORITY_RANK[m["triage_priority"]] for m in members), default=1)
        priority = [p for p, r in PRIORITY_RANK.items() if r == rank][0]
        det = c["determination_date"]
        start_clock = first or c["opened_date"]
        a2d = max(0, ((det or as_of) - start_clock).days)
        filing_days = (c["filing_date"] - det).days if c["filing_date"] and det else None
        prior_sar_days = None
        if c["parent"] is not None and c["filing_date"] is not None:
            prior_sar_days = (c["filing_date"] - c["parent"]["filing_date"]).days
        if c["close_date"] is not None:
            status = "closed"
        elif det is not None:
            status = "pending_filing"
        else:
            status = "open"
        out_cases.append(
            {
                "case_id": c["case_id"],
                "customer_id": customer_id,
                "case_type": c["case_type"],
                "parent_case_id": c["parent"]["case_id"] if c["parent"] else None,
                "opened_date": c["opened_date"],
                "crr_tier": crr_tier,
                "priority": priority,
                "alert_count": len(members),
                "escalated_alert_count": c["escalated"],
                "rule_ids": sorted({m["rule_id"] for m in members}),
                "first_alert_date": first,
                "activity_window_start": add_months(c["opened_date"], -lookback),
                "activity_window_end": c["opened_date"],
                "case_status": status,
                "determination": c["determination"],
                "determination_date": det,
                "sar_decision": c["sar_decision"],
                "suspect_identified": bool(c["suspect"]),
                "regulatory_limit": c["regulatory_limit"],
                "filing_deadline_date": c["filing_deadline"],
                "filing_date": c["filing_date"],
                "determination_to_filing_days": filing_days,
                "days_since_prior_sar": prior_sar_days,
                "filed_late": (
                    c["filing_date"] > c["filing_deadline"]
                    if c["filing_date"] and c["filing_deadline"]
                    else None
                ),
                "alert_to_decision_days": a2d,
                "sla_breached": a2d > sla,
                "continuing_review_due_date": c["review_due"],
                "continuing_review_status": c["review_status"],
                "continuing_review_case_id": c["review_case_id"],
                "simulated_truth": bool(c["truth"]),
            }
        )
    return dispositions, out_cases


