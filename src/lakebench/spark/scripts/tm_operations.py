def _write_recon(spark, rows, base_run_id, cycle, cycle_run_id, as_of):
    from decimal import Decimal

    from pyspark.sql.functions import current_timestamp, lit

    schema = "section STRING, item STRING, unit STRING, item_count BIGINT, amount_usd DECIMAL(38,2)"
    data = [
        (
            s,
            i,
            u,
            int(c) if c is not None else None,
            Decimal(str(a)).quantize(Decimal("0.01")) if a is not None else None,
        )
        for s, i, u, c, a in rows
    ]
    df = spark.createDataFrame(data, schema).select(
        lit(base_run_id).alias("run_id"),
        lit(cycle).cast("int").alias("cycle"),
        lit(cycle_run_id).alias("cycle_run_id"),
        lit(as_of).cast("date").alias("as_of_date"),
        "section",
        "item",
        "unit",
        "item_count",
        "amount_usd",
        current_timestamp().alias("computed_ts"),
    )
    t = f"{CATALOG}.{GOLD_RECON}"
    # This run's history only, one set of rows per cycle or tick; a rerun of
    # the same cycle replaces its own rows.
    safe_run = base_run_id.replace("'", "''")
    spark.sql(f"DELETE FROM {t} WHERE run_id <> '{safe_run}' OR cycle = {int(cycle)}")
    df.writeTo(t).append()


def _ledger_cycles(spark, base_run_id):
    """{cycle: as_of_date} already in the ledger for this run."""
    from pyspark.sql.functions import col, lit
    from pyspark.sql.functions import max as max_

    try:
        return {
            int(r["cycle"]): r["a"]
            for r in spark.table(f"{CATALOG}.{GOLD_RECON}")
            .where(col("run_id") == lit(base_run_id))
            .groupBy("cycle")
            .agg(max_("as_of_date").alias("a"))
            .collect()
        }
    except Exception as e:  # noqa: BLE001
        log(f"[tm] ledger unreadable: {one_line(e)}")
        return {}


def _prior_state(spark, base_run_id, cycle, ledger):
    """The previous cycle's dispositions and cases (pinned snapshots) to
    carry forward, its as-of date, and whether this is a rerun of the same
    cycle. (None, None, None, False) on a first cycle or another run's
    tables."""
    from pyspark.sql.functions import col, lit
    from pyspark.sql.functions import max as max_
    from pyspark.sql.functions import min as min_

    dt, ct = f"{CATALOG}.{GOLD_DISPOSITIONS}", f"{CATALOG}.{GOLD_CASES}"
    dsid, csid = current_snapshot_id(spark, dt), current_snapshot_id(spark, ct)
    if dsid is None:
        return None, None, None, False
    pdisp = read_at_snapshot(spark, dt, dsid)
    pcases = read_at_snapshot(spark, ct, csid) if csid is not None else None
    meta = pdisp.agg(
        min_("base_run_id").alias("lo"),
        max_("base_run_id").alias("hi"),
        max_("cycle").alias("c"),
        max_("as_of_date").alias("a"),
    ).collect()[0]
    if meta["lo"] is None or meta["lo"] != base_run_id or meta["hi"] != base_run_id:
        return None, None, None, False
    prior_cycle = int(meta["c"])
    if prior_cycle < cycle:
        prev_as_of = meta["a"]
    elif prior_cycle == cycle:
        # A rerun of this cycle: carry only what earlier cycles saw, dated by
        # the ledger's previous cycle.
        earlier = [c for c in ledger if c < cycle]
        if not earlier:
            return None, None, None, False
        prev_as_of = ledger[max(earlier)]
        pdisp = pdisp.where(col("first_seen_cycle") < lit(cycle))
        if pcases is not None:
            pcases = pcases.where(col("opened_date") <= lit(prev_as_of))
    else:
        return None, None, None, False
    if prev_as_of is None:
        return None, None, None, False
    return pdisp, pcases, prev_as_of, prior_cycle == cycle


def _status(status, cycle, reason):
    log(f"[tm-status] status={status} cycle={cycle} reason={one_line(reason, limit=400)}")


def run_tm_operations(
    spark,
    txns,
    run_id,
    *,
    cycle=None,
    continuous=False,
    params=None,
    source_rows_fn=None,
    rule_targets=None,
    txns_table=None,
):
    """Stages 1, 6, 7 and 8 for one cycle, then the invariant check.

    Never raises. Returns the list of (name, status, detail) invariants, or a
    single ``workflow`` entry with status ``not_run`` or ``disabled`` (with
    the reason) when the layer did not run. ``txns`` is only a fallback: the
    silver table (``txns_table``) is read at one pinned snapshot.
    """
    from pyspark.sql.functions import col, current_timestamp, lit, timestamp_micros
    from pyspark.sql.functions import max as max_

    params = dict(params or params_from_env())
    params.setdefault("counterparty_scenarios", DEFAULT_COUNTERPARTY_SCENARIOS)
    base_run_id, cycle_no = split_run_id(run_id, cycle)
    if not params.get("enabled", True):
        reason = "workload.tm_operations.enabled is false"
        try:
            # Empty tables, so readers (the investigator queries) still resolve.
            bootstrap_tm_tables(spark)
        except Exception as e:  # noqa: BLE001
            log(f"[tm] bootstrap skipped: {one_line(e)}")
        _status("disabled", cycle_no, reason)
        return [("workflow", "disabled", reason)]
    import time

    started = time.time()
    held = []
    try:
        if rule_targets is None:
            from detection_rules import RULE_TARGET_TYPOLOGY

            rule_targets = dict(RULE_TARGET_TYPOLOGY)
        bootstrap_tm_tables(spark)
        ledger = _ledger_cycles(spark, base_run_id)
        tick = None
        if continuous:
            # One ledger set per operations pass, numbered from the ledger so a
            # restarted gold-refresh driver appends instead of overwriting.
            tick = cycle_no
            cycle_no = max(ledger, default=0) + 1
            cycle_run_id = f"{run_id}-t{cycle_no}"
        else:
            cycle_run_id = run_id

        # Silver at one snapshot, pinned BEFORE the source is counted: every
        # payment in it was written by datagen before the count started.
        table = f"{CATALOG}.{txns_table or SILVER_TXNS}"
        sid = current_snapshot_id(spark, table)
        if sid is not None:
            txns = read_at_snapshot(spark, table, sid)
        else:
            log(f"[tm] {table} has no snapshot to pin; reading the frame as passed")
        newest = txns.agg(max_(col("txn_timestamp")).alias("m")).collect()[0]["m"]
        if newest is None:
            reason = f"{table} is empty; nothing to monitor"
            _status("not_run", cycle_no, reason)
            return [("workflow", "not_run", reason)]
        as_of = newest.date() + timedelta(days=1)
        entities = spark.table(f"{CATALOG}.{SILVER_ENTITIES}")
        manifest = _read_manifest(spark)
        if manifest is None:
            reason = (
                f"no ground-truth manifest ({MANIFEST_TABLE}); dispositions cannot be simulated"
            )
            _status("not_run", cycle_no, reason)
            return [("workflow", "not_run", reason)]

        # Stage 1: completeness.
        source_rows = (source_rows_fn or count_source_rows)(spark)
        bronze_rows, _ = iceberg_table_stats(spark, f"{CATALOG}.{BRONZE_TABLE}")
        recon_rows, recon = reconcile(spark, txns, entities, source_rows, bronze_rows, continuous)

        # The previous cycle, pinned before this cycle overwrites it.
        prior_disp, prior_cases, prev_as_of, rerun = _prior_state(
            spark, base_run_id, cycle_no, ledger
        )
        carry = None
        if prior_disp is not None:
            # Customers only, and only those still customers: an entity that
            # left the monitored population has its alerts out of scope now.
            still = entities.where(col("is_customer") == lit(True)).select("entity_id").distinct()
            carry = prior_disp.where(
                col("is_customer") & (col("disposition") != lit(DISP_OVER_CAPACITY))
            ).join(still, "entity_id", "left_semi")
            prior_disp = prior_disp.join(still, "entity_id", "left_semi")

        # Stage 6-8: triage, cases, SAR decisions.
        alerts = spark.table(f"{CATALOG}.{GOLD_ALERTS}").where(col("run_id") == lit(run_id))
        inputs = build_alert_inputs(spark, alerts, entities, manifest, params, carry).persist()
        held.append(inputs)
        disp_sim, cases_sim, tagged = simulate(
            spark, inputs, carry, params, as_of, prev_as_of, cycle_no
        )
        held.append(tagged)
        run_cols = [
            lit(as_of).cast("date").alias("as_of_date"),
            lit(cycle_no).cast("int").alias("cycle"),
            lit(base_run_id).alias("base_run_id"),
            lit(run_id).alias("run_id"),
            current_timestamp().alias("computed_ts"),
        ]
        declared = list(params.get("counterparty_scenarios") or ())
        disp_cols = [n for n, _ in ddl_columns(DDL_DISPOSITIONS)][:-5]
        sim_rows = (
            disp_sim.withColumn("alert_ts", timestamp_micros(col("alert_ts")))
            .withColumn("is_customer", lit(True))
            .withColumn(
                "declared_counterparty",
                col("rule_id").isin(declared) if declared else lit(False),
            )
        )
        # Alerts the replay does not work: on a non-customer (outside the
        # monitored population) or over the per-customer cap.
        other = inputs.where(~col("is_customer") | col("over_capacity")).select(
            "alert_id",
            "alert_key",
            "rule_id",
            "entity_id",
            "is_customer",
            "declared_counterparty",
            "crr_tier",
            "scenario_weight",
            "priority_score",
            "triage_priority",
            "alert_ts",
            "content_hash",
            lit(None).cast("int").alias("first_seen_cycle"),
            lit(None).cast("date").alias("first_seen_as_of"),
            lit(True).alias("in_current_detection"),
            "generated_date",
            lit(None).cast("date").alias("l1_decision_date"),
            _when_customer(lit(DISP_OVER_CAPACITY), lit(DISP_OUT_OF_SCOPE)).alias("disposition"),
            lit("closed").alias("queue_status"),
            lit(None).cast("string").alias("case_id"),
            col("generated_date").alias("decision_date"),
            lit(0).alias("aging_days"),
            lit(False).alias("sla_breached"),
            "simulated_truth",
            lit(None).cast("boolean").alias("analyst_correct"),
            lit(False).alias("qa_sampled"),
            lit(None).cast("string").alias("qa_disposition"),
            lit(None).cast("boolean").alias("qa_disagrees"),
        )
        disp = sim_rows.select(*disp_cols).unionByName(other.select(*disp_cols))
        disp.select(*disp_cols, *run_cols).writeTo(f"{CATALOG}.{GOLD_DISPOSITIONS}").overwrite(
            lit(True)
        )
        activity = case_activity(txns, cases_sim)
        case_cols = [n for n, _ in ddl_columns(DDL_CASES)][:-5]
        cases = cases_sim.join(activity, "case_id", "left").withColumn(
            "activity_txn_count", _coalesce_long("activity_txn_count")
        )
        cases.select(*case_cols, *run_cols).writeTo(f"{CATALOG}.{GOLD_CASES}").overwrite(lit(True))

        # Scenario coverage matrix.
        try:
            status_rows = [
                r.asDict()
                for r in spark.table(f"{CATALOG}.{GOLD_STATUS}")
                .where(col("run_id") == lit(run_id))
                .collect()
            ]
        except Exception as e:  # noqa: BLE001
            log(f"[tm] detection_status not readable: {one_line(e)}")
            status_rows = []
        cov = coverage_rows(spark, inputs, status_rows, manifest, rule_targets)
        spark.createDataFrame(
            cov,
            "typology STRING, rule_id STRING, coverage STRING, rule_status STRING, "
            "alert_count BIGINT, customer_alert_count BIGINT, planted_instances BIGINT",
        ).select(
            "*", lit(run_id).alias("run_id"), current_timestamp().alias("computed_ts")
        ).writeTo(f"{CATALOG}.{GOLD_COVERAGE}").overwrite(lit(True))

        # Read the written tables back once; the funnel rows complete the
        # cycle ledger, and the invariants read the ledger as written.
        counts = read_back(spark, run_id, as_of, prior_disp, prior_cases, prev_as_of, rerun)
        recon_rows = recon_rows + [
            ("funnel", "alerts", "alerts", counts["customer_alerts"], None),
            ("funnel", "alerts_out_of_scope", "alerts", counts["noncustomer_alerts"], None),
            (
                "funnel",
                "alerts_noncustomer_undeclared",
                "alerts",
                counts["noncustomer_undeclared"],
                None,
            ),
            ("funnel", "escalated", "alerts", counts["escalated"], None),
            ("funnel", "cases", "cases", counts["alert_cases"], None),
            ("funnel", "continuing_review_cases", "cases", counts["review_cases"], None),
            ("funnel", "sars", "sars", counts["alert_sars"], None),
            ("funnel", "continuing_sars", "sars", counts["review_sars"], None),
        ]
        _write_recon(spark, recon_rows, base_run_id, cycle_no, cycle_run_id, as_of)
        rec = {
            (r["section"], r["item"]): r["item_count"]
            for r in spark.table(f"{CATALOG}.{GOLD_RECON}")
            .where((col("run_id") == lit(base_run_id)) & (col("cycle") == lit(cycle_no)))
            .collect()
        }
        src = rec.get(("completeness", "source"))
        counts.update(
            {
                "negative_items": sorted(
                    f"{s}.{i}={v}" for (s, i), v in rec.items() if v is not None and v < 0
                ),
                "source": None if src is None else int(src),
                "customers": int(rec.get(("completeness", "customers")) or 0),
                "silver": int(rec.get(("completeness", "silver")) or 0),
                "monitored": int(rec.get(("completeness", "monitored")) or 0),
                "excluded": int(rec.get(("completeness", "excluded")) or 0),
            }
        )
        invariants = evaluate_invariants(counts)
        summary = ops_summary(as_of, params, recon_rows, counts)
    except Exception as e:  # noqa: BLE001 -- reported through the gate
        err = one_line(f"{type(e).__name__}: {e}", limit=400)
        _status("not_run", cycle_no, f"error: {err}")
        return [("workflow", "not_run", f"error: {err}")]
    finally:
        for df in held:
            try:
                df.unpersist()
            except Exception:  # noqa: BLE001
                pass

    _status("ran", cycle_no, "ok")
    for name, status, detail in invariants:
        log(f"[tm-invariant] {name}: status={status} cycle={cycle_no} detail={detail}")
    summary["cycle"] = cycle_no
    if tick is not None:
        summary["gold_refresh_tick"] = tick
    summary["elapsed_seconds"] = round(time.time() - started, 1)
    summary["invariants"] = {n: {"status": s, "detail": d} for n, s, d in invariants}
    log("[tm-ops] " + json.dumps(summary, sort_keys=True, default=str))
    return invariants


def _when_customer(yes, no):
    from pyspark.sql.functions import col, when

    return when(col("is_customer"), yes).otherwise(no)


def _coalesce_long(name):
    from pyspark.sql.functions import coalesce, col, lit

    return coalesce(col(name), lit(0)).cast("bigint")
